#!/usr/bin/env python3
"""Rasterize opencreator-oc-white.svg into src/logo.c as LVGL ALPHA_8BIT images.

Usage: python3 scripts/gen-logo.py [SVG] [OUT_C]
"""
import re
import sys

SIZES = {"oc_logo_small": 56, "oc_logo_large": 240}
SS = 4


def parse(svg):
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
    d = re.search(r'\sd="([^"]+)"', svg).group(1)
    polys = []
    for sub in re.split(r"[Zz]", d):
        pts = [(float(x), float(y)) for x, y in re.findall(r"[ML]\s*([-\d.]+)[ ,]+([-\d.]+)", sub)]
        if len(pts) > 2:
            polys.append(pts)
    return vb, polys


def rasterize(vb, polys, width):
    vx, vy, vw, vh = vb
    height = round(width * vh / vw)
    sw, sh = width * SS, height * SS
    sx, sy = sw / vw, sh / vh
    edges = []
    for pts in polys:
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            x0, y0 = (x0 - vx) * sx, (y0 - vy) * sy
            x1, y1 = (x1 - vx) * sx, (y1 - vy) * sy
            if y0 != y1:
                edges.append((x0, y0, x1, y1))
    cover = [[0] * width for _ in range(height)]
    for row in range(sh):
        yc = row + 0.5
        xs = sorted(x0 + (yc - y0) * (x1 - x0) / (y1 - y0)
                    for x0, y0, x1, y1 in edges
                    if min(y0, y1) <= yc < max(y0, y1))
        line = cover[row // SS]
        for a, b in zip(xs[0::2], xs[1::2]):
            for col in range(max(0, int(a + 0.5)), min(sw, int(b + 0.5))):
                line[col // SS] += 1
    full = SS * SS
    return width, height, [min(255, c * 255 // full) for r in cover for c in r]


def emit(name, w, h, data):
    out = [f"static const uint8_t {name}_map[] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const lv_img_dsc_t {name} = {{")
    out.append(f"    .header.cf = LV_IMG_CF_ALPHA_8BIT, .header.always_zero = 0,")
    out.append(f"    .header.w = {w}, .header.h = {h},")
    out.append(f"    .data_size = sizeof({name}_map), .data = {name}_map,")
    out.append("};")
    return "\n".join(out)


def main():
    svg_path = sys.argv[1] if len(sys.argv) > 1 else "opencreator-oc-white.svg"
    out_path = sys.argv[2] if len(sys.argv) > 2 else "src/logo.c"
    vb, polys = parse(open(svg_path).read())
    parts = ["/* Generated by scripts/gen-logo.py from opencreator-oc-white.svg. */",
             '#include "lvgl/lvgl.h"', '#include "logo.h"', ""]
    for name, width in SIZES.items():
        parts.append(emit(name, *rasterize(vb, polys, width)))
        parts.append("")
    open(out_path, "w").write("\n".join(parts))


if __name__ == "__main__":
    main()
