"""The OpenAD5X logo for the installer and the AD5X boot screen, from one drawing:
an orange O with the A over its right side, the same as openad5x docs/assets/logo.svg.

Writes src/logo_ad5x.c (LVGL ALPHA_8BIT layers, the O and the A; main.c colours
each one) and payload-template/common/logo-ad5x.jpeg (800x480, landscape like the
AD5X panel).

Usage: python3 scripts/gen-logo-ad5x.py
Needs Pillow.
"""
import os

from PIL import Image, ImageDraw, ImageFont

# docs/assets/logo.svg: viewBox -2 18 127 79; the O is a 12 wide ring
# (centre 36,57.5, radius 27.5); the A is a polygon with a triangular counter.
VIEW_X, VIEW_Y, VIEW_W, VIEW_H = -2.0, 18.0, 127.0, 79.0
O_CENTRE, O_OUTER, O_INNER = (36.0, 57.5), 33.5, 21.5
A_SHAPE = [(41.04, 91.0), (81.04, 24.0), (121.04, 91.0), (107.06, 91.0),
           (99.30, 78.0), (62.78, 78.0), (55.02, 91.0)]
A_COUNTER = [(81.04, 47.41), (92.14, 66.0), (69.94, 66.0)]

SS = 8
SIZES = {"ad5x_logo_small": 56, "ad5x_logo_large": 240}
BOOT_SIZE = (800, 480)
BOOT_MARK_WIDTH = 300
BOOT_BACKGROUND = (0x15, 0x1A, 0x22)
ORANGE = (0xFF, 0x57, 0x22)
OFF_WHITE = (0xF5, 0xF2, 0xEC)


def layer(part, width):
    """Coverage mask (mode L) of the O or the A at this width."""
    height = round(width * VIEW_H / VIEW_W)
    scale = width * SS / VIEW_W
    pt = lambda x, y: ((x - VIEW_X) * scale, (y - VIEW_Y) * scale)
    mask = Image.new("L", (width * SS, height * SS), 0)
    draw = ImageDraw.Draw(mask)
    if part == "o":
        for radius, fill in ((O_OUTER, 255), (O_INNER, 0)):
            (x0, y0), (x1, y1) = (pt(O_CENTRE[0] - radius, O_CENTRE[1] - radius),
                                  pt(O_CENTRE[0] + radius, O_CENTRE[1] + radius))
            draw.ellipse((x0, y0, x1, y1), fill=fill)
    else:
        draw.polygon([pt(x, y) for x, y in A_SHAPE], fill=255)
        draw.polygon([pt(x, y) for x, y in A_COUNTER], fill=0)
    return mask.resize((width, height), Image.BOX)


def emit(name, mask):
    data = mask.tobytes()
    out = [f"static const uint8_t {name}_map[] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const lv_img_dsc_t {name} = {{")
    out.append("    .header.cf = LV_IMG_CF_ALPHA_8BIT, .header.always_zero = 0,")
    out.append(f"    .header.w = {mask.width}, .header.h = {mask.height},")
    out.append(f"    .data_size = sizeof({name}_map), .data = {name}_map,")
    out.append("};")
    return "\n".join(out)


def boot_logo(root, path):
    image = Image.new("RGB", BOOT_SIZE, BOOT_BACKGROUND)
    o, a = layer("o", BOOT_MARK_WIDTH), layer("a", BOOT_MARK_WIDTH)
    font = ImageFont.truetype(os.path.join(
        root, "vendor", "lvgl", "scripts", "built_in_font", "Montserrat-Medium.ttf"), 46)
    text = "OpenAD5X"
    left, top, right, bottom = font.getbbox(text)
    gap = 34
    top_y = (BOOT_SIZE[1] - o.height - gap - (bottom - top)) // 2
    x = (BOOT_SIZE[0] - o.width) // 2
    image.paste(ORANGE, (x, top_y, x + o.width, top_y + o.height), o)
    image.paste(OFF_WHITE, (x, top_y, x + a.width, top_y + a.height), a)
    ImageDraw.Draw(image).text(
        ((BOOT_SIZE[0] - (right - left)) // 2 - left, top_y + o.height + gap - top),
        text, font=font, fill=OFF_WHITE)
    image.save(path, "JPEG", quality=92, optimize=True)
    print(path, image.size)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parts = ["/* Generated by scripts/gen-logo-ad5x.py: the OpenAD5X OA mark, the O and",
             " * the A as separate layers so main.c can colour each one. */",
             '#include "lvgl/lvgl.h"', '#include "logo_ad5x.h"', ""]
    for name, width in SIZES.items():
        for part in ("o", "a"):
            parts.append(emit(f"{name}_{part}", layer(part, width)))
            parts.append("")
    path = os.path.join(root, "src", "logo_ad5x.c")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(parts))
    print(path)
    boot_logo(root, os.path.join(root, "payload-template", "common", "logo-ad5x.jpeg"))


if __name__ == "__main__":
    main()
